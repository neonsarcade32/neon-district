'use strict';
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const url=process.env.ARCADE_TEST_URL||'http://127.0.0.1:8080';
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true,args:['--use-angle=swiftshader','--enable-webgl','--disable-web-security']});
 const page=await browser.newPage({viewport:{width:1280,height:800}});
 const errors=[];
 page.on('pageerror',e=>errors.push('PAGE: '+e.message));
 page.on('console',msg=>{if(msg.type()==='error')errors.push('CONSOLE: '+msg.text())});
 const response=await page.goto(url+'/neon-freeski.html',{waitUntil:'domcontentloaded',timeout:35000});
 assert.equal(response.status(),200,'Game URL must serve HTTP 200');
 await page.waitForFunction(()=>document.getElementById('loading').hidden===true,{timeout:35000});
 const ready=await page.evaluate(()=>window.__neonFreeskiDebug?.state);
 assert.ok(ready,'Debug API should be available');
 assert.equal(ready.features,6,'Six kickers are created');
 assert.equal(ready.rails,5,'Five grind rails are created');
 assert.equal(ready.started,false);
 assert.ok(await page.locator('canvas').count()>0,'Three.js canvas must exist');
 await page.locator('#start').click();
 await page.waitForTimeout(650);
 const s1=await page.evaluate(()=>window.__neonFreeskiDebug.state);
 assert.ok(s1.started&&!s1.paused,'Game must start');
 await page.keyboard.down('w'); await page.waitForTimeout(1000); await page.keyboard.up('w');
 const s2=await page.evaluate(()=>window.__neonFreeskiDebug.state);
 assert.ok(s2.z>s1.z+5,'Player moves downhill');
 assert.ok(s2.speed>=s1.speed,'Tuck accelerates on slope');
 await page.keyboard.down('Space');await page.waitForTimeout(470);await page.keyboard.up('Space');
 await page.waitForTimeout(160);
 const s3=await page.evaluate(()=>window.__neonFreeskiDebug.state);
 assert.ok(s3.airborne,'Charging and releasing jump should launch player');
 await page.keyboard.down('d');await page.waitForTimeout(320);await page.keyboard.up('d');
 await page.screenshot({path:'neon-freeski-qa.png'});
 await page.keyboard.press('p');
 await page.waitForTimeout(150);
 const s4=await page.evaluate(()=>window.__neonFreeskiDebug.state);
 assert.ok(s4.paused,'P should pause game');
 await page.locator('#start').click();await page.waitForTimeout(200);
 const s5=await page.evaluate(()=>window.__neonFreeskiDebug.state);
 assert.ok(!s5.paused,'Resume should work');
 await browser.close();
 assert.deepEqual(errors,[],'No browser JS errors');
 console.log('PASS Neon Freeski 3D browser: WebGL renders; game starts; skier moves and accelerates; jump launches; pause and resume work; screenshot saved.');
})().catch(e=>{console.error('FAIL Neon Freeski browser',e.stack||e);process.exitCode=1});
